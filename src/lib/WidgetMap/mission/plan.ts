/* План миссии генератора: контуры, параметры проходов, полёта и распыления */
import type { LngLat, SprayControl } from "./coverage"

/* Поле: контур и свой угол проходов */
export interface IMissionField {
  contour: LngLat[]
  angle: number /* Направление проходов, ° от севера по часовой */
}

export interface IMissionPlan {
  fields: IMissionField[] /* Поля; облетаются по очереди от ближайшего */
  holes: LngLat[][] /* Запретные зоны */
  start?: LngLat /* Точка взлёта */
  spacing: number /* Ширина захвата, м */
  margin: number /* Отступ от границ и зон, м */
  alt: number /* Высота полёта, м */
  speed: number /* Скорость, м/с */
  returnHome: boolean
  rate: number /* Норма внесения, л/га */
  tank: number /* Объём бака, л */
  sprayControl: SprayControl /* Как миссия включает и выключает распыление */
  servoChannel: number
  servoOn: number
  servoOff: number
}

